CREATE TABLE IF NOT EXISTS MINUTA_ASISTENTES (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    MINUTA_ID BIGINT NOT NULL,
    USUARIO_ID BIGINT NULL,
    NOMBRE VARCHAR(200) NOT NULL,
    CORREO VARCHAR(254) NULL,
    ROL VARCHAR(100) NOT NULL,
    ESTADO_ASISTENCIA VARCHAR(20) NOT NULL DEFAULT 'Convocado',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_MINUTA_ASISTENTE_USUARIO (MINUTA_ID, USUARIO_ID),
    KEY IX_ASISTENTES_USUARIO (USUARIO_ID),
    CONSTRAINT FK_ASISTENTES_MINUTA FOREIGN KEY (MINUTA_ID) REFERENCES MINUTAS(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MINUTA_TEMAS (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    MINUTA_ID BIGINT NOT NULL,
    ORDEN INT NOT NULL,
    TEMA VARCHAR(250) NOT NULL,
    DESCRIPCION TEXT NULL,
    RESPONSABLE_ID BIGINT NULL,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_MINUTA_TEMA_ORDEN (MINUTA_ID, ORDEN),
    CONSTRAINT FK_TEMAS_MINUTA FOREIGN KEY (MINUTA_ID) REFERENCES MINUTAS(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MINUTA_ACUERDOS (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    MINUTA_ID BIGINT NOT NULL,
    TEMA_ID BIGINT NULL,
    TIPO VARCHAR(20) NOT NULL,
    DESCRIPCION TEXT NOT NULL,
    ORDEN INT NOT NULL DEFAULT 1,
    REGISTRADO_POR BIGINT NOT NULL,
    FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID),
    KEY IX_ACUERDOS_MINUTA (MINUTA_ID, ORDEN),
    CONSTRAINT FK_ACUERDOS_MINUTA FOREIGN KEY (MINUTA_ID) REFERENCES MINUTAS(ID),
    CONSTRAINT FK_ACUERDOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES MINUTA_TEMAS(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MINUTA_TAREAS (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    MINUTA_ID BIGINT NOT NULL,
    ACUERDO_ID BIGINT NULL,
    DESCRIPCION TEXT NOT NULL,
    RESPONSABLE_ID BIGINT NOT NULL,
    FECHA_LIMITE DATE NOT NULL,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    FECHA_FINALIZACION DATETIME NULL,
    EVIDENCIA TEXT NULL,
    CREADO_POR BIGINT NOT NULL,
    FECHA_CREACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHA_ACTUALIZACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID),
    KEY IX_TAREAS_RESPONSABLE_ESTADO (RESPONSABLE_ID, ESTADO, FECHA_LIMITE),
    KEY IX_TAREAS_MINUTA (MINUTA_ID),
    CONSTRAINT FK_TAREAS_MINUTA FOREIGN KEY (MINUTA_ID) REFERENCES MINUTAS(ID),
    CONSTRAINT FK_TAREAS_ACUERDO FOREIGN KEY (ACUERDO_ID) REFERENCES MINUTA_ACUERDOS(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
