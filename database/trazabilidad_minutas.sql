-- Fase de trazabilidad: ejecutar una sola vez sobre la base de datos existente.
-- No modifica ni elimina datos de las minutas aprobadas.

CREATE TABLE IF NOT EXISTS `MNTRZ` (
    `MNTRZ_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `MNTRZ_ORIGEN_ID` BIGINT NOT NULL,
    `MNTRZ_DESTINO_ID` BIGINT NOT NULL,
    `MNTRZ_USR_ID` BIGINT NOT NULL,
    `MNTRZ_FN` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`MNTRZ_ID`),
    UNIQUE KEY `UK_MNTRZ_ORIGEN_DESTINO` (`MNTRZ_ORIGEN_ID`, `MNTRZ_DESTINO_ID`),
    KEY `IX_MNTRZ_DESTINO` (`MNTRZ_DESTINO_ID`),
    CONSTRAINT `FK_MNTRZ_ORIGEN` FOREIGN KEY (`MNTRZ_ORIGEN_ID`) REFERENCES `MNTA` (`MNTA_ID`),
    CONSTRAINT `FK_MNTRZ_DESTINO` FOREIGN KEY (`MNTRZ_DESTINO_ID`) REFERENCES `MNTA` (`MNTA_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `MNTRZT` (
    `MNTRZT_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `MNTRZT_RELACION_ID` BIGINT NOT NULL,
    `MNTRZT_TAREA_ORIGEN_ID` BIGINT NOT NULL,
    `MNTRZT_TAREA_DESTINO_ID` BIGINT NOT NULL,
    `MNTRZT_ACUERDO_ORIGEN_ID` BIGINT NULL,
    `MNTRZT_ACUERDO_DESTINO_ID` BIGINT NULL,
    `MNTRZT_TAREA_ORIGEN_DESC` TEXT NOT NULL,
    `MNTRZT_TAREA_DESTINO_DESC` TEXT NOT NULL,
    `MNTRZT_ACUERDO_ORIGEN_DESC` TEXT NULL,
    `MNTRZT_ACUERDO_DESTINO_DESC` TEXT NULL,
    PRIMARY KEY (`MNTRZT_ID`),
    UNIQUE KEY `UK_MNTRZT_TAREA_ORIGEN_DESTINO` (`MNTRZT_RELACION_ID`, `MNTRZT_TAREA_ORIGEN_ID`),
    UNIQUE KEY `UK_MNTRZT_TAREA_DESTINO` (`MNTRZT_TAREA_DESTINO_ID`),
    KEY `IX_MNTRZT_TAREA_ORIGEN` (`MNTRZT_TAREA_ORIGEN_ID`),
    CONSTRAINT `FK_MNTRZT_RELACION` FOREIGN KEY (`MNTRZT_RELACION_ID`) REFERENCES `MNTRZ` (`MNTRZ_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
