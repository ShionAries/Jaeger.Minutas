CREATE TABLE IF NOT EXISTS MINUTA_AUDITORIA (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    MINUTA_ID BIGINT NOT NULL,
    USUARIO_ID INT(11) NOT NULL,
    ACCION VARCHAR(40) NOT NULL,
    FECHA_EVENTO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATOS_ANTERIORES LONGTEXT NULL,
    DATOS_NUEVOS LONGTEXT NULL,
    PRIMARY KEY (ID),
    KEY IX_MINUTA_AUDITORIA_MINUTA_FECHA (MINUTA_ID, FECHA_EVENTO),
    KEY IX_MINUTA_AUDITORIA_USUARIO_FECHA (USUARIO_ID, FECHA_EVENTO),
    CONSTRAINT FK_MINUTA_AUDITORIA_MINUTA FOREIGN KEY (MINUTA_ID) REFERENCES MINUTAS (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
